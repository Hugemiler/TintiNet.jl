# 06_prepare_chains.jl — read every downloaded structure once and, for each
# selected chain, write (a) a per-residue table of what we can compute
# ourselves and (b) the chain as a small PDB-format file for STRIDE.
#
# READS    work/index/chains.tsv                 which chains are selected
#          work/raw/mmCIF/<ab>/<1abc>.cif.gz     the structures
# WRITES   work/tools/chains/<ab>.arrow          per-residue table, one file per folder
#          work/tools/chains/<ab>.chains.tsv     one row per chain: what happened
#          work/tools/chain_pdb/<ab>/<1abc>_<asym>.pdb.gz
#
# RUN      julia -t 16 --project=scripts/data scripts/data/06_prepare_chains.jl
#          julia -t 16 --project=scripts/data scripts/data/06_prepare_chains.jl cx c7
#          julia -t 16 --project=scripts/data scripts/data/06_prepare_chains.jl --force
#
# Structures are stored in folders named after the two middle characters of
# the identifier (1abc is in ab/). This script works one folder at a time and
# skips folders it has already finished. Name folders to do only those; pass
# --force to redo them.
#
# Columns of the per-residue table
#   pdb_id, chain_id     chain_id as in chains.tsv
#   asym_id              the chain's name inside the mmCIF file (can differ)
#   seq_index            position in the full sequence, starting at 1
#   residue              three-letter residue name from the sequence record
#   observed             true if the residue has coordinates (a CA atom)
#   phi, psi, omega      backbone angles in degrees, computed here from
#                        coordinates; NaN where they cannot be computed
#   ca_bfactor           B-factor of the CA atom
#   min_occupancy        lowest occupancy among the residue's kept atoms
#   has_altloc           true if the residue has alternate conformations
#   ca_x, ca_y, ca_z     CA coordinates
#   cb_x, cb_y, cb_z     CB coordinates (CA for glycine or when CB is missing)
#   contacts_6, contacts_12, contacts_24
#                        number of residues of the SAME chain within
#                        CONTACT_DISTANCE whose sequence separation is at
#                        least 6, 12, 24
#   contacts_other       number of residues of OTHER chains in the file within
#                        CONTACT_DISTANCE
#
# Rules this script applies (change them here, in one place)
#   * Only the first model of a file is used.
#   * Alternate conformations: per residue we keep atoms that have no
#     alternate label, plus the atoms of the one alternate label with the
#     highest total occupancy.
#   * Distances are measured between CB atoms (CA for glycine).
#   * "Other chains" means other chains written in the same file. Copies
#     generated by crystal symmetry are not included.

include("common.jl")
include("mmcif.jl")
using Arrow
using LinearAlgebra
using Printf

# ---- knobs -----------------------------------------------------------------
const CONTACT_DISTANCE = 8.0            # ångström, between CB atoms
const MAX_PDB_RESIDUE_NUMBER = 9999     # the PDB format cannot hold more
# ----------------------------------------------------------------------------

const CHAINS_TABLE  = joinpath(INDEX_DIR, "chains.tsv")
const MMCIF_DIR     = joinpath(RAW_DIR, "mmCIF")
const CHAINS_OUT    = joinpath(TOOLS_DIR, "chains")
const CHAIN_PDB_DIR = joinpath(TOOLS_DIR, "chain_pdb")

const Point = NTuple{3, Float64}

struct Atom
    name::String
    element::String
    altloc::String
    position::Point
    occupancy::Float64
    bfactor::Float64
end

# ----------------------------------------------------------------------------
# Geometry
# ----------------------------------------------------------------------------

minus(a::Point, b::Point) = (a[1] - b[1], a[2] - b[2], a[3] - b[3])
distance(a::Point, b::Point) = norm(minus(a, b))

"Dihedral angle a-b-c-d in degrees, in the range -180 to 180."
function dihedral(a::Point, b::Point, c::Point, d::Point)
    b1, b2, b3 = collect(minus(b, a)), collect(minus(c, b)), collect(minus(d, c))
    n1, n2 = cross(b1, b2), cross(b2, b3)
    m1 = cross(b2 / norm(b2), n1)
    # Sign convention checked against STRIDE on entry 1c75 (helix: phi and psi
    # both negative).
    return rad2deg(atan(dot(m1, n2), dot(n1, n2)))
end

# ----------------------------------------------------------------------------
# Reading one structure
# ----------------------------------------------------------------------------

const WANTED_TABLES = Dict(
    "_pdbx_poly_seq_scheme" => ["asym_id", "seq_id", "mon_id", "pdb_strand_id"],
    "_atom_site" => ["type_symbol", "label_atom_id", "label_alt_id", "label_asym_id",
                     "label_seq_id", "Cartn_x", "Cartn_y", "Cartn_z",
                     "occupancy", "B_iso_or_equiv", "pdbx_PDB_model_num"],
)

"""
Keep one conformation of a residue: atoms with no alternate label, plus the
atoms of the alternate label with the highest total occupancy.
"""
function choose_conformation(atoms::Vector{Atom})
    labels = unique(atom.altloc for atom in atoms if atom.altloc != ".")
    isempty(labels) && return atoms, false
    total(label) = sum(atom.occupancy for atom in atoms if atom.altloc == label)
    best = argmax(total, sort(labels))          # ties go to the first label alphabetically
    return [atom for atom in atoms if atom.altloc == "." || atom.altloc == best], true
end

"Position of the atom called `name`, or `nothing`."
function position_of(atoms::Vector{Atom}, name)
    for atom in atoms
        atom.name == name && return atom.position
    end
    return nothing
end

"""
Read one mmCIF file and return, for every polymer chain in it:
  sequences[asym]         three-letter residue names, by sequence position
  chain_names[asym]       the chain's name as used in chains.tsv
  atoms[asym][seq_index]  the atoms of each residue that has coordinates
"""
function read_structure(path)
    tables = read_cif_tables(path, WANTED_TABLES)
    haskey(tables, "_pdbx_poly_seq_scheme") || error("no sequence table in file")
    haskey(tables, "_atom_site")            || error("no atom table in file")

    # --- sequences ------------------------------------------------------------
    scheme      = tables["_pdbx_poly_seq_scheme"]
    sequences   = Dict{String, Vector{String}}()
    chain_names = Dict{String, String}()
    for row in 1:cif_rows(scheme)
        asym      = scheme["asym_id"][row]
        seq_index = parse(Int, scheme["seq_id"][row])
        sequence  = get!(sequences, asym, String[])
        chain_names[asym] = scheme["pdb_strand_id"][row]
        # A position can be listed twice when two residue types share it
        # (rare). We keep the first.
        seq_index == length(sequence) + 1 && push!(sequence, scheme["mon_id"][row])
    end

    # --- atoms ----------------------------------------------------------------
    site  = tables["_atom_site"]
    atoms = Dict{String, Dict{Int, Vector{Atom}}}()
    nrows = cif_rows(site)
    first_model = nrows == 0 ? "1" : site["pdbx_PDB_model_num"][1]
    for row in 1:nrows
        site["pdbx_PDB_model_num"][row] == first_model || continue
        seq_text = site["label_seq_id"][row]
        seq_text == "." && continue                      # not part of a polymer (water, ligand)
        asym = site["label_asym_id"][row]
        haskey(sequences, asym) || continue
        residue_atoms = get!(get!(atoms, asym, Dict{Int, Vector{Atom}}()),
                             parse(Int, seq_text), Atom[])
        push!(residue_atoms, Atom(
            site["label_atom_id"][row],
            site["type_symbol"][row],
            site["label_alt_id"][row],
            (parse(Float64, site["Cartn_x"][row]),
             parse(Float64, site["Cartn_y"][row]),
             parse(Float64, site["Cartn_z"][row])),
            something(tryparse(Float64, site["occupancy"][row]), 1.0),
            something(tryparse(Float64, site["B_iso_or_equiv"][row]), NaN),
        ))
    end
    return sequences, chain_names, atoms
end

# ----------------------------------------------------------------------------
# Contacts: a grid so we never compare every residue with every other
# ----------------------------------------------------------------------------

cell_of(p::Point) = (floor(Int, p[1] / CONTACT_DISTANCE),
                     floor(Int, p[2] / CONTACT_DISTANCE),
                     floor(Int, p[3] / CONTACT_DISTANCE))

"The point that stands for a residue when measuring contacts."
function contact_point(atoms::Vector{Atom})
    for name in ("CB", "CA", "C4'", "P")        # proteins first, then nucleic acids
        p = position_of(atoms, name)
        p === nothing || return p
    end
    return nothing
end

# ----------------------------------------------------------------------------
# One entry -> rows and PDB files
# ----------------------------------------------------------------------------

"Text of one chain in PDB format, numbered by sequence position, chain named A."
function pdb_text(sequence, residues::Dict{Int, Vector{Atom}})
    io = IOBuffer()
    serial = 0
    for seq_index in sort(collect(keys(residues)))
        residue_name = sequence[seq_index]
        for atom in residues[seq_index]
            atom.element in ("H", "D") && continue
            serial += 1
            # PDB atom names: 4 columns. Names of up to three characters start
            # in the second column unless the element symbol has two letters.
            name = length(atom.name) >= 4 || length(atom.element) == 2 ?
                   rpad(atom.name, 4) : " " * rpad(atom.name, 3)
            @printf(io, "ATOM  %5d %s %3s A%4d    %8.3f%8.3f%8.3f%6.2f%6.2f          %2s\n",
                    serial % 100000, name, last(residue_name, 3), seq_index,
                    atom.position..., atom.occupancy,
                    isnan(atom.bfactor) ? 0.0 : min(atom.bfactor, 999.99), atom.element)
        end
    end
    println(io, "END")
    return String(take!(io))
end

"Process one entry. Returns its residue rows and one status row per selected chain."
function prepare_entry(pdb_id, path, selected_chain_ids, pdb_folder)
    residue_rows = NamedTuple[]
    chain_rows   = NamedTuple[]

    sequences, chain_names, all_atoms = read_structure(path)

    # One contact point per residue, for every polymer chain in the file.
    points = Tuple{String, Int, Point}[]              # (asym, seq_index, position)
    kept   = Dict{String, Dict{Int, Vector{Atom}}}()  # atoms after choosing a conformation
    altloc = Dict{Tuple{String, Int}, Bool}()
    for (asym, residues) in all_atoms
        kept[asym] = Dict{Int, Vector{Atom}}()
        for (seq_index, atoms) in residues
            chosen, had_altloc = choose_conformation(atoms)
            kept[asym][seq_index] = chosen
            altloc[(asym, seq_index)] = had_altloc
            p = contact_point(chosen)
            p === nothing || push!(points, (asym, seq_index, p))
        end
    end
    grid = Dict{NTuple{3, Int}, Vector{Int}}()
    for (i, (_, _, p)) in enumerate(points)
        push!(get!(grid, cell_of(p), Int[]), i)
    end

    for (asym, sequence) in sequences
        chain_id = chain_names[asym]
        chain_id in selected_chain_ids || continue
        residues = get(kept, asym, Dict{Int, Vector{Atom}}())

        backbone(seq_index, name) = haskey(residues, seq_index) ?
                                    position_of(residues[seq_index], name) : nothing

        n_observed = 0
        for seq_index in eachindex(sequence)
            atoms = get(residues, seq_index, Atom[])
            n, ca, c = backbone(seq_index, "N"), backbone(seq_index, "CA"), backbone(seq_index, "C")
            observed = ca !== nothing
            n_observed += observed

            # Backbone angles need atoms from the neighbouring residues.
            previous_c  = backbone(seq_index - 1, "C")
            previous_ca = backbone(seq_index - 1, "CA")
            next_n      = backbone(seq_index + 1, "N")
            complete    = n !== nothing && ca !== nothing && c !== nothing
            phi   = complete && previous_c !== nothing ? dihedral(previous_c, n, ca, c) : NaN
            psi   = complete && next_n !== nothing     ? dihedral(n, ca, c, next_n)     : NaN
            omega = n !== nothing && ca !== nothing && previous_c !== nothing && previous_ca !== nothing ?
                    dihedral(previous_ca, previous_c, n, ca) : NaN

            # Contacts.
            point = isempty(atoms) ? nothing : contact_point(atoms)
            c6 = c12 = c24 = other = 0
            if point !== nothing
                cx, cy, cz = cell_of(point)
                for dx in -1:1, dy in -1:1, dz in -1:1
                    for i in get(grid, (cx + dx, cy + dy, cz + dz), ())
                        other_asym, other_index, other_point = points[i]
                        distance(point, other_point) <= CONTACT_DISTANCE || continue
                        if other_asym != asym
                            other += 1
                        else
                            separation = abs(other_index - seq_index)
                            c6  += separation >= 6
                            c12 += separation >= 12
                            c24 += separation >= 24
                        end
                    end
                end
            end

            cb = point === nothing ? (NaN, NaN, NaN) : point
            ca_atom = findfirst(a -> a.name == "CA", atoms)
            push!(residue_rows, (
                pdb_id = pdb_id, chain_id = chain_id, asym_id = asym,
                seq_index = Int32(seq_index), residue = sequence[seq_index],
                observed = observed,
                phi = Float32(phi), psi = Float32(psi), omega = Float32(omega),
                ca_bfactor = Float32(ca_atom === nothing ? NaN : atoms[ca_atom].bfactor),
                min_occupancy = Float32(isempty(atoms) ? NaN : minimum(a.occupancy for a in atoms)),
                has_altloc = get(altloc, (asym, seq_index), false),
                ca_x = Float32(observed ? ca[1] : NaN), ca_y = Float32(observed ? ca[2] : NaN),
                ca_z = Float32(observed ? ca[3] : NaN),
                cb_x = Float32(cb[1]), cb_y = Float32(cb[2]), cb_z = Float32(cb[3]),
                contacts_6 = Int16(c6), contacts_12 = Int16(c12), contacts_24 = Int16(c24),
                contacts_other = Int16(other),
            ))
        end

        # The chain as a PDB-format file, for STRIDE.
        problem = "none"
        if n_observed == 0
            problem = "no coordinates"
        elseif length(sequence) > MAX_PDB_RESIDUE_NUMBER
            problem = "too long for PDB format"
        else
            mkpath(pdb_folder)
            # Gzipped: uncompressed, these files would add up to about 60 GB.
            open(GzipCompressorStream, joinpath(pdb_folder, pdb_id * "_" * asym * ".pdb.gz"), "w") do io
                write(io, pdb_text(sequence, residues))
            end
        end
        push!(chain_rows, (pdb_id = pdb_id, chain_id = chain_id, asym_id = asym,
                           length = length(sequence), observed = n_observed, problem = problem))
    end
    return residue_rows, chain_rows
end

# ----------------------------------------------------------------------------
# One folder of entries
# ----------------------------------------------------------------------------

function prepare_folder(folder, selected_by_entry)
    residue_rows = NamedTuple[]
    chain_rows   = NamedTuple[]
    for file in sort(readdir(joinpath(MMCIF_DIR, folder)))
        endswith(file, ".cif.gz") || continue
        pdb_id = first(split(file, '.'))
        haskey(selected_by_entry, pdb_id) || continue
        try
            rows, chains = prepare_entry(pdb_id, joinpath(MMCIF_DIR, folder, file),
                                         selected_by_entry[pdb_id],
                                         joinpath(CHAIN_PDB_DIR, folder))
            append!(residue_rows, rows)
            append!(chain_rows, chains)
        catch err
            push!(chain_rows, (pdb_id = pdb_id, chain_id = "", asym_id = "", length = 0,
                               observed = 0,
                               problem = "failed: " * first(sprint(showerror, err), 150)))
        end
    end
    isempty(chain_rows) && return 0, 0

    mkpath(CHAINS_OUT)
    # Write the residue table last and under a temporary name first: its
    # presence is what marks the folder as finished.
    CSV.write(joinpath(CHAINS_OUT, folder * ".chains.tsv"), DataFrame(chain_rows); delim = '\t')
    partial = joinpath(CHAINS_OUT, folder * ".arrow.part")
    Arrow.write(partial, DataFrame(residue_rows); compress = :zstd)
    mv(partial, joinpath(CHAINS_OUT, folder * ".arrow"); force = true)
    return length(chain_rows), length(residue_rows)
end

function main(arguments)
    force   = "--force" in arguments
    named   = filter(a -> !startswith(a, "--"), arguments)
    folders = isempty(named) ? sort(readdir(MMCIF_DIR)) : named

    say("reading ", relpath(CHAINS_TABLE, REPO_ROOT), " ...")
    chains   = read_table(CHAINS_TABLE)
    selected = filter(:selected => identity, chains)
    selected_by_entry = Dict{String, Set{String}}()
    for row in eachrow(selected)
        push!(get!(selected_by_entry, row.pdb_id, Set{String}()), string(row.chain_id))
    end

    missing_folders = filter(f -> !isdir(joinpath(MMCIF_DIR, f)), folders)
    isempty(missing_folders) || say("no such folder, skipped: ", join(missing_folders, " "))
    folders = filter(f -> isdir(joinpath(MMCIF_DIR, f)), folders)

    todo = [f for f in folders if force || !isfile(joinpath(CHAINS_OUT, f * ".arrow"))]
    say(length(folders), " folders, ", length(todo), " to do, using ",
        Threads.nthreads(), " threads")

    finished = Threads.Atomic{Int}(0)
    total_chains   = Threads.Atomic{Int}(0)
    total_residues = Threads.Atomic{Int}(0)
    Threads.@threads :dynamic for folder in todo
        n_chains, n_residues = try
            prepare_folder(folder, selected_by_entry)
        catch err
            # One bad folder must not stop the others. It stays unfinished, so
            # the next run tries it again.
            say("folder ", folder, " failed: ", first(sprint(showerror, err), 200))
            (0, 0)
        end
        Threads.atomic_add!(total_chains, n_chains)
        Threads.atomic_add!(total_residues, n_residues)
        n = Threads.atomic_add!(finished, 1) + 1
        n % 25 == 0 && say(n, " of ", length(todo), " folders")
    end
    say("done: ", total_chains[], " chains, ", total_residues[], " residues")
end

main(ARGS)
